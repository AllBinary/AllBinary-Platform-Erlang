tan(This, Angle) when is_integer(Angle) ->
        array:get(Angle, get({This, noDecimalTan})).

% throws Exception
antiTan(This, Dx, Dy) when is_integer(Dx), is_integer(Dy) ->
        try
        MAX_VALUE = (trunc(get({'Integer', 'MAX_VALUE'}))),
        MIN_VALUE = (trunc(get({'Integer', 'MIN_VALUE'}))),
        put({local, ratio}, ((MAX_VALUE - 1))),
        case (Dy =/= 0) of
            true ->
            Dxl = (Dx),
            put({local, ratio}, ((get({This, 'SCALE'}) * Dxl) div Dy)),
            case ((Dx =< 0) andalso (Dy < 0)) of
                true ->
                put({local, ratio}, (get({get({This, mathUtil}), '$class'})):abslong(get({This, mathUtil}), get({local, ratio})));
                false -> ok
            end;
            false -> ok
        end,
        case (((Dx >= 0) andalso (Dy < 0))) of
            true ->
            lists:foreach(fun(Index) ->
                case (get({local, ratio}) =< array:get(Index, get({This, noDecimalTan}))) of
                    true ->
                    case (get({local, ratio}) > array:get((Index - 1), get({This, noDecimalTan}))) of
                        true ->
                        throw({'$return', (Index)});
                        false ->
                        case ((array:get((Index - 1), get({This, noDecimalTan})) =:= MAX_VALUE) andalso (get({local, ratio}) > MIN_VALUE)) of
                        true ->
                        throw({'$return', (Index)});
                        false -> ok
                    end
                    end;
                    false -> ok
                end
            end, lists:seq(180, 90 + 1, -1));
            false ->
            case (((Dx < 0) andalso (Dy =< 0))) of
            true ->
            lists:foreach(fun(Index) ->
                case ((get({local, ratio}) < array:get(Index, get({This, noDecimalTan}))) andalso (get({local, ratio}) >= array:get((Index - 1), get({This, noDecimalTan})))) of
                    true ->
                    throw({'$return', (Index)});
                    false -> ok
                end
            end, lists:seq(270, 180 + 1, -1));
            false ->
            case (((Dx < 0) andalso (Dy > 0))) of
            true ->
            lists:foreach(fun(Index) ->
                case (get({local, ratio}) < array:get(Index, get({This, noDecimalTan}))) of
                    true ->
                    case (get({local, ratio}) >= array:get((Index - 1), get({This, noDecimalTan}))) of
                        true ->
                        throw({'$return', (Index)});
                        false ->
                        case ((array:get((Index - 1), get({This, noDecimalTan})) =:= MAX_VALUE) andalso (get({local, ratio}) >= MIN_VALUE)) of
                        true ->
                        throw({'$return', (Index)});
                        false -> ok
                    end
                    end;
                    false -> ok
                end
            end, lists:seq(((array:size(get({This, noDecimalTan})) - 1)), 270 + 1, -1));
            false ->
            case (((Dx >= 0) andalso (Dy >= 0))) of
            true ->
            lists:foreach(fun(Index) ->
                case ((get({local, ratio}) < array:get(Index, get({This, noDecimalTan}))) andalso (get({local, ratio}) >= array:get((Index - 1), get({This, noDecimalTan})))) of
                    true ->
                    throw({'$return', (Index)});
                    false -> ok
                end
            end, lists:seq(90, 0 + 1, -1));
            false -> ok
        end
        end
        end
        end,
        StringBuffer = 'StringMaker':new(),
        (get({StringBuffer, '$class'})):append(StringBuffer, "Invalid Ratio: "),
        (get({StringBuffer, '$class'})):appendlong(StringBuffer, get({local, ratio})),
        (get({StringBuffer, '$class'})):append(StringBuffer, get({'CommonSeps':getInstance(), 'SPACE'})),
        (get({StringBuffer, '$class'})):append(StringBuffer, get({'PositionStrings':getInstance(), 'DX_LABEL'})),
        (get({StringBuffer, '$class'})):appendint(StringBuffer, Dx),
        (get({StringBuffer, '$class'})):append(StringBuffer, get({'CommonSeps':getInstance(), 'SPACE'})),
        (get({StringBuffer, '$class'})):append(StringBuffer, get({'PositionStrings':getInstance(), 'DX_LABEL'})),
        (get({StringBuffer, '$class'})):appendint(StringBuffer, Dy),
        erlang:error({'Exception', (get({StringBuffer, '$class'})):toString(StringBuffer)})
        catch throw:{'$return', ReturnValue} -> ReturnValue end.

